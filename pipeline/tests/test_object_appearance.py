"""Tests for object.py's appearance stage and reconstruction-model provenance (no network, no GPU)."""

from __future__ import annotations

import argparse
import io
from pathlib import Path

import numpy as np
import pytest
import trimesh

from tests.test_texture_project import (  # reuse the synthetic ground-truth scene
    GRAY, _frame, _glb_with_texture, _ground_truth_texture, _pose, _striped_tube,
)
from worldkit import appearance, texture_project
from worldkit import object as obj


class _Frame:  # stands in for frames.Frame: the stage only needs .path
    def __init__(self, path: Path):
        self.path = path


def _args(backend="trellis", project_frames=None) -> argparse.Namespace:
    return argparse.Namespace(mesh_backend=backend, project_frames=project_frames)


@pytest.fixture
def scene_glb(tmp_path: Path):
    verts, faces, uvs = _striped_tube()
    gt = _ground_truth_texture()
    base = np.full((128, 256, 3), GRAY, dtype=np.uint8)
    path = tmp_path / "model.glb"
    path.write_bytes(_glb_with_texture(verts, faces, uvs, base))
    frames = [
        texture_project.FrameInput(f"f{az}", *(lambda v: (v.rgb, v.mask))(_frame(f"f{az}", verts, faces, uvs, gt, _pose(float(az), 35.0))))
        for az in (0, 70, 140, 210, 280)
    ]
    return path, frames


def _final_mesh(path: Path):
    return list(trimesh.load(io.BytesIO(path.read_bytes()), file_type="glb", process=False).geometry.values())[0]


def test_provenance_never_attributes_a_non_meta_model_to_meta():
    assert obj.RECONSTRUCTION_MODELS["modal"]["is_meta_model"] is True
    assert obj.RECONSTRUCTION_MODELS["trellis"]["is_meta_model"] is False
    assert obj.RECONSTRUCTION_MODELS["hosted"]["is_meta_model"] is False
    assert obj.RECONSTRUCTION_MODELS["import"]["is_meta_model"] is None  # unknown, never assumed
    assert obj.RECONSTRUCTION_MODELS["trellis"]["vendor"] == "Microsoft"


def test_untextured_glb_passes_through_unchanged(tmp_path: Path):
    path = tmp_path / "model.glb"
    path.write_bytes(trimesh.creation.box().export(file_type="glb"))
    before, report = path.read_bytes(), {"warnings": []}

    out = obj._appearance_stage(path, _args("hosted"), report, [], "mug", None)

    assert out == path and path.read_bytes() == before
    assert report["appearance"]["textured"] is False


def test_non_glb_meshes_are_not_touched(tmp_path: Path):
    path = tmp_path / "model.obj"
    path.write_text("v 0 0 0\nv 1 0 0\nv 0 1 0\nf 1 2 3\n")
    report = {"warnings": []}

    assert obj._appearance_stage(path, _args("import"), report, [], "mug", None) == path
    assert "appearance" not in report


def test_finalize_only_when_projection_is_off(scene_glb, monkeypatch):
    path, _ = scene_glb
    called = []
    monkeypatch.setattr(obj.texture_project, "reproject_frames_onto_glb", lambda *a, **k: called.append(1))
    report = {"warnings": []}

    out = obj._appearance_stage(path, _args("import"), report, [], "mug", None)  # import defaults to 0 frames

    assert called == []  # a mesh we did not generate is never repainted unless asked
    assert report["appearance"]["texture_source"] == "generated by the reconstruction model"
    assert "projection" not in report["appearance"]
    assert report["appearance"]["finalize"]["vertex_normals_added"] is True
    assert _final_mesh(out).extents.max() == pytest.approx(2.0, rel=1e-3)  # viewer-sized


def test_projection_replaces_generated_texels_with_real_pixels(scene_glb, monkeypatch):
    path, frames = scene_glb
    monkeypatch.setattr(obj.video_appearance, "build_frame_inputs", lambda paths, name: (frames, []))
    report = {"warnings": []}

    out = obj._appearance_stage(path, _args("trellis"), report, [_Frame(Path(f"{f.name}.png")) for f in frames], "mug", "f0")

    proj = report["appearance"]["projection"]
    assert proj["geometry_modified"] is False and proj["anchor_frame"] == "f0"
    assert proj["observed_fraction"] > 0.4
    assert report["appearance"]["texture_source"] == "generated + real video pixels where observed"
    assert any("real video pixels" in w and "generated" in w for w in report["warnings"])
    tex = np.array(_final_mesh(out).visual.material.baseColorTexture.convert("RGB")).astype(float)
    assert np.abs(tex - GRAY).mean() > 20.0  # genuinely repainted


def test_projection_is_skipped_with_a_warning_when_too_few_frames_segment(scene_glb, monkeypatch):
    path, frames = scene_glb
    skipped = [{"frame": "x", "reason": "only the local fallback mask was available (not concept-aware)"}]
    monkeypatch.setattr(obj.video_appearance, "build_frame_inputs", lambda paths, name: (frames[:1], skipped))
    report = {"warnings": []}

    out = obj._appearance_stage(path, _args("trellis"), report, [_Frame(Path("a.png"))], "mug", None)

    assert "projection" not in report["appearance"]
    assert report["appearance"]["frames_skipped"] == skipped
    assert any("skipped" in w and "need >= 2" in w for w in report["warnings"])
    assert appearance.glb_is_textured(out.read_bytes())  # the mesh is still finalized, just not repainted


def test_trellis_defaults_to_projecting_8_frames_and_import_to_none(scene_glb, monkeypatch):
    path, frames = scene_glb
    monkeypatch.setattr(obj.video_appearance, "build_frame_inputs", lambda paths, name: (frames, []))
    seen = {}

    def spy(glb, inputs, *, anchor, max_views, texture_format):
        seen["max_views"], seen["anchor"], seen["fmt"] = max_views, anchor, texture_format
        return glb, {"observed_fraction": 0.5, "generated_fraction": 0.5}

    monkeypatch.setattr(obj.texture_project, "reproject_frames_onto_glb", spy)

    obj._appearance_stage(path, _args("trellis"), {"warnings": []}, [], "mug", "f0")
    assert seen == {"max_views": 8, "anchor": "f0", "fmt": "JPEG"}

    seen.clear()
    obj._appearance_stage(path, _args("import"), {"warnings": []}, [], "mug", None)
    assert seen == {}  # no projection for imported meshes unless --project-frames is given

    obj._appearance_stage(path, _args("import", project_frames=3), {"warnings": []}, [], "mug", None)
    assert seen["max_views"] == 3


def test_anchor_name_not_among_usable_frames_falls_back_to_auto(scene_glb, monkeypatch):
    path, frames = scene_glb
    monkeypatch.setattr(obj.video_appearance, "build_frame_inputs", lambda paths, name: (frames, []))
    seen = {}
    monkeypatch.setattr(
        obj.texture_project, "reproject_frames_onto_glb",
        lambda glb, inputs, **kw: (seen.update(kw), (glb, {"observed_fraction": 0.5, "generated_fraction": 0.5}))[1],
    )

    obj._appearance_stage(path, _args("trellis"), {"warnings": []}, [], "mug", "sharp_09_not_segmented")

    assert seen["anchor"] is None  # the frame TRELLIS used failed segmentation: let the fit choose
